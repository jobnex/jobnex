import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {run} from './certified-helpers.mjs';
import {sourceDigest} from './source-digest.mjs';
const gate=process.argv[2];
const token={render:'CERTIFIED_RENDER_VERIFIED',api:'CERTIFIED_API_VERIFIED',build:'CERTIFIED_BUILD_VERIFIED'}[gate];
assert.ok(token,'Specify render, api, or build');
const evidence=JSON.parse(readFileSync('test-evidence/cloud-build.json','utf8'));
assert.match(evidence.buildId,/^[0-9a-f-]{36}$/);
assert.equal(evidence.project,'job-scout-508222');assert.equal(evidence.region,'us-east1');
assert.equal(sourceDigest(),evidence.sourceDigest,'Source changed since the Linux verification build');
const args=['proxy','gcloud','builds','describe',evidence.buildId,'--project='+evidence.project,'--region='+evidence.region,'--format=json'];
const result=JSON.parse((await run('rtk',args)).stdout);
assert.equal(result.status,'SUCCESS','Linux test build must complete successfully');
const log=(await run('rtk',['proxy','gcloud','builds','log',evidence.buildId,'--project='+evidence.project,'--region='+evidence.region])).stdout;
assert.ok(log.includes('CERTIFIED_SOURCE_SHA256='+evidence.sourceDigest),'Uploaded source digest must match the current backend');
assert.ok(log.includes(token),'The corresponding runtime test suite must pass in the Linux build');
if(gate==='build')assert.ok(log.includes('test result: ok.'),'Rust unit tests must also pass');
console.log(token);
