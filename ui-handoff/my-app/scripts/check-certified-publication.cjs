const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
require(path.join(root,'node_modules/tsx/dist/cjs/index.cjs'));
const {validateResumeDocument,documentToEditor,applyEditorText,canonicalJson}=require(path.join(root,'lib/resume-document.ts'));
const {document}=JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/canonical-resume.json'),'utf8'));
validateResumeDocument(document);
const editor=documentToEditor(document);
assert.match(editor.skills[0].items,/Observability \(Prometheus, Grafana\)/);
assert.deepEqual(applyEditorText(document,structuredClone(editor)),document);
const changed=structuredClone(editor);changed.personalInfo.name='Changed identity';changed.experience[0].company='Changed employer';changed.skills[0].items='Unknown skill';
assert.deepEqual(applyEditorText(document,changed),document);
const invalid=structuredClone(document);invalid.experience[0].bullets[0].evidenceIds=['missing'];assert.throws(()=>validateResumeDocument(invalid));
const duplicate=structuredClone(document);duplicate.sectionOrder.push('skills');assert.throws(()=>validateResumeDocument(duplicate));
assert.equal(canonicalJson({z:'Café',a:1}),'{"a":1,"z":"Café"}');
const modal=fs.readFileSync(path.join(root,'components/CertifiedResumeModal.tsx'),'utf8');
assert.ok(modal.includes('crypto.subtle.digest("SHA-256",bytes)'));
assert.ok(modal.includes('checkedBytes(publication,true)'));
assert.ok(!modal.includes('parseResumeMarkdown'));
const server=fs.readFileSync(path.join(root,'lib/resume-publication-server.ts'),'utf8');
assert.ok(server.includes('/api/v2/jobs/'));
assert.ok(!server.includes('ui-export')&&!server.includes('generateResumeDownloadUrl'));
console.log('CERTIFIED_UI_CONTRACT_VERIFIED');
